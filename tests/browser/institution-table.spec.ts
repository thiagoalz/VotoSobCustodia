import { expect, test } from "@playwright/test";

test("navega para a tabela, filtra Papuda e mostra votos e percentuais nos dois recortes sem rede externa", async ({ page }, testInfo) => {
  const errors: string[] = [], external: string[] = [];
  const origin = new URL(testInfo.project.use.baseURL!).origin;
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/*", route => {
    if (new URL(route.request().url()).origin !== origin) { external.push(route.request().url()); return route.abort(); }
    return route.continue();
  });
  await page.goto("./");
  if (testInfo.project.name === "mobile") await page.getByRole("button", { name: "Abrir navegação" }).click();
  await page.getByRole("link", { name: "Tabela geral", exact: true }).click();
  await expect(page).toHaveURL(/\/tabela\/?$/);
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Instituições e seus municípios.");
  await expect(page.getByRole("combobox", { name: "Eleição", exact: true })).toHaveValue("2026");
  await expect(page.getByRole("combobox", { name: "Turno", exact: true })).toHaveValue("2");
  await expect(page.locator(".voting-table tbody tr")).toHaveCount(243);
  await expect(page.getByRole("status")).toContainText("243 instituições · 190 municípios");
  await page.getByRole("combobox", { name: "Eleição", exact: true }).selectOption("2022");
  await page.getByLabel("Buscar instituição ou município").fill("papuda");
  const row = page.locator(".voting-table tbody tr");
  await expect(row).toHaveCount(1);
  await expect(row.locator('[data-column="unit-votes-22"]')).toHaveText("57");
  await expect(row.locator('[data-column="unit-percent-22"]')).toHaveText("54,29%");
  await expect(row.locator('[data-column="city-votes-22"]')).toHaveText("1.041.331");
  await expect(row.locator('[data-column="city-percent-22"]')).toHaveText("58,81%");
  await expect(row.locator('[data-column="unit-valid"]')).toHaveText("105");
  await expect(row.locator('[data-column="city-total"]')).toHaveText("1.838.492");
  await expect(row.locator('[data-column="municipality"]')).toHaveText("BRASÍLIA");
  await page.getByRole("combobox", { name: "Turno", exact: true }).selectOption("1");
  await expect(row.locator('[data-column="unit-votes-22"]')).toHaveText("59");
  await expect(page.locator(".voting-groups")).toContainText("SIMONE NASSAR TEBET");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(await page.locator(".voting-scroll").evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true);
  await page.getByRole("link", { name: "Voltar ao site", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1 })).toContainText("O direito ao voto");
  expect(errors).toEqual([]); expect(external).toEqual([]);
});

test("ordena campos numéricos e textuais, exporta o recorte e conserva lacunas", async ({ page }) => {
  await page.goto("./tabela/");
  await page.getByRole("combobox", { name: "Estado", exact: true }).selectOption("DF");
  const rows = page.locator(".voting-table tbody tr");
  expect(await rows.count()).toBeGreaterThan(1);
  const sort = page.getByRole("combobox", { name: "Ordenar por", exact: true });
  await sort.selectOption("unit-percent-22");
  const values = () => rows.locator('[data-column="unit-percent-22"]').allTextContents().then(items => items.map(value => Number(value.replace("%", "").replace(",", "."))));
  const asc = await values(); expect(asc).toEqual([...asc].sort((a, b) => a - b));
  await page.getByRole("button", { name: "Ordem crescente; mudar para decrescente", exact: true }).click();
  const desc = await values(); expect(desc).toEqual([...desc].sort((a, b) => b - a));
  await expect(page.locator('thead [data-column="unit-percent-22"]')).toHaveAttribute("aria-sort", "descending");
  const municipality = page.getByRole("button", { name: "Ordenar por Identificação — Município", exact: true });
  await municipality.click();
  await expect(page.locator('thead [data-column="municipality"]')).toHaveAttribute("aria-sort", "ascending");
  await municipality.click();
  await expect(page.locator('thead [data-column="municipality"]')).toHaveAttribute("aria-sort", "descending");
  await sort.selectOption("city-votes-22");
  const expectedNames = await rows.locator('[data-column="name"]').allTextContents();
  const event = page.waitForEvent("download");
  await page.getByRole("button", { name: "Baixar tabela CSV", exact: true }).click();
  const download = await event;
  expect(download.suggestedFilename()).toBe("instituicoes-municipios-2026-turno-2.csv");
  const stream = await download.createReadStream(); const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const csv = Buffer.concat(chunks).toString("utf8");
  expect(csv).toContain("FLAVIO NANTES BOLSONARO — Votos no município");
  const lines = csv.split("\r\n").slice(1).filter(Boolean);
  expect(lines.map(line => line.split(";")[3])).toEqual(expectedNames);
  await page.getByLabel("Buscar instituição ou município").fill("zzzinexistente");
  await expect(page.getByText("Nenhuma instituição neste recorte", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Baixar tabela CSV", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Limpar busca e filtros", exact: true }).click();
  await expect(rows).toHaveCount(243);
  await page.getByRole("combobox", { name: "Eleição", exact: true }).selectOption("2022");
  await page.getByLabel("Buscar instituição ou município").fill("COMPLEXO PENITENCIARIO DO PURAQUEQUARA");
  await expect(rows).toHaveCount(1);
  await expect(rows.locator('[data-column="unit-votes-22"]')).toHaveText("—");
  await expect(rows.locator('[data-column="unit-percent-22"]')).toHaveText("—");
  await expect(rows.locator('[data-column="city-votes-22"]')).not.toHaveText("—");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
